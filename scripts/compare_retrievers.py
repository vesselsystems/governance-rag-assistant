"""Compare TF-IDF and BM25 on the regression set and the pre-registered challenge set.

Writes reports/retriever_comparison.json and reports/retriever_comparison.md.
The output contains no timestamps or git state, so identical inputs produce
identical files; `--check` exits non-zero when the committed reports are stale.

    python scripts/compare_retrievers.py          # regenerate both reports
    python scripts/compare_retrievers.py --check  # verify committed reports (CI)
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

from governance_rag.comparison import compare, mcnemar_exact
from governance_rag.corpus import load_manifest, verify_manifest
from governance_rag.retrieval import Bm25Retriever, TfidfRetriever

ROOT = Path(__file__).resolve().parents[1]
CHALLENGE = ROOT / "evaluation" / "challenge_questions.json"
REGRESSION = ROOT / "evaluation" / "questions.json"
MANIFEST = ROOT / "data" / "corpus_manifest.json"
JSON_REPORT = ROOT / "reports" / "retriever_comparison.json"
MARKDOWN_REPORT = ROOT / "reports" / "retriever_comparison.md"
SETTINGS = {
    "tfidf": "TfidfVectorizer(stop_words='english', ngram_range=(1, 2)), cosine similarity",
    "bm25": "Okapi BM25, k1=1.5, b=0.75, same tokenizer and stop words, unigrams",
}


def _sha256_text(path: Path) -> str:
    # Hash with normalised line endings so Windows and Linux checkouts agree.
    text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def build_report() -> dict:
    verify_manifest(load_manifest(MANIFEST), ROOT / "data" / "documents")
    challenge_file = json.loads(CHALLENGE.read_text(encoding="utf-8"))
    challenge = challenge_file["questions"]
    regression = json.loads(REGRESSION.read_text(encoding="utf-8"))
    top_k = int(challenge_file["protocol"]["top_k"])
    retrievers = {
        "tfidf": TfidfRetriever.from_directory(ROOT / "data" / "documents"),
        "bm25": Bm25Retriever.from_directory(ROOT / "data" / "documents"),
    }
    label_counts: dict[str, int] = {}
    for item in challenge:
        label_counts[item["label_status"]] = label_counts.get(item["label_status"], 0) + 1
    results = {
        name: {"settings": SETTINGS[name], **compare(challenge, regression, retriever, top_k)}
        for name, retriever in retrievers.items()
    }
    tfidf_rows, bm25_rows = results["tfidf"]["rows"], results["bm25"]["rows"]
    return {
        "protocol": challenge_file["protocol"],
        "inputs": {
            "challenge_questions_sha256": _sha256_text(CHALLENGE),
            "regression_questions_sha256": _sha256_text(REGRESSION),
            "corpus_manifest_sha256": _sha256_text(MANIFEST),
            "indexed_chunks": len(retrievers["tfidf"].chunks),
            "challenge_questions": len(challenge),
            "challenge_label_status": dict(sorted(label_counts.items())),
            "regression_questions": len(regression),
        },
        "paired_tests_post_hoc": {
            "comparison": "first=tfidf, second=bm25, all answerable challenge questions",
            "hit_at_1": mcnemar_exact(tfidf_rows, bm25_rows, max_rank=1),
            "hit_at_3": mcnemar_exact(tfidf_rows, bm25_rows, max_rank=3),
        },
        "retrievers": results,
    }


def _fmt(value: object) -> str:
    if value is None:
        return "n/a"
    if isinstance(value, float):
        return f"{value:.2f}"
    return str(value)


def _short(citation: str) -> str:
    source, _, chunk = citation.strip("[]").partition("#")
    stem = "ppn017" if source.startswith("ppn_017") else source.split("_")[0]
    return f"{stem}#{chunk}"


def render_markdown(report: dict) -> str:
    inputs = report["inputs"]
    tfidf = report["retrievers"]["tfidf"]
    bm25 = report["retrievers"]["bm25"]
    labels = ", ".join(
        f"{count} {status}" for status, count in inputs["challenge_label_status"].items()
    )
    lines = [
        "# Retriever comparison: TF-IDF vs BM25",
        "",
        "Generated by `python scripts/compare_retrievers.py`; do not edit by hand.",
        f"Corpus: {inputs['indexed_chunks']} chunks. Regression set: "
        f"{inputs['regression_questions']} questions. Challenge set: "
        f"{inputs['challenge_questions']} questions ({labels}).",
        "The protocol (settings, metrics, threshold rule) is recorded in",
        "`evaluation/challenge_questions.json` and was fixed before these numbers existed.",
        "",
        "## Ranking quality (chunk level, answerable questions)",
        "",
        "| Question set | n | TF-IDF hit@1 | TF-IDF hit@3 | TF-IDF MRR | "
        "BM25 hit@1 | BM25 hit@3 | BM25 MRR |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    sets = [
        ("Original regression set", "regression_set"),
        ("Challenge dev", "challenge_dev"),
        ("Challenge test", "challenge_test"),
        ("Challenge, both splits", "challenge_all"),
    ]
    for label, key in sets:
        a, b = tfidf[key], bm25[key]
        lines.append(
            f"| {label} | {a['answerable_questions']} | {_fmt(a['hit_at_1'])} | "
            f"{_fmt(a['hit_at_3'])} | {_fmt(a['mrr_at_3'])} | {_fmt(b['hit_at_1'])} | "
            f"{_fmt(b['hit_at_3'])} | {_fmt(b['mrr_at_3'])} |"
        )
    for design, a in tfidf["challenge_by_design"].items():
        b = bm25["challenge_by_design"][design]
        lines.append(
            f"| Challenge (all splits): {design} | {a['answerable_questions']} | "
            f"{_fmt(a['hit_at_1'])} | {_fmt(a['hit_at_3'])} | {_fmt(a['mrr_at_3'])} | "
            f"{_fmt(b['hit_at_1'])} | {_fmt(b['hit_at_3'])} | {_fmt(b['mrr_at_3'])} |"
        )
    paired = report["paired_tests_post_hoc"]
    lines += [
        "",
        "Paired exact McNemar test over the same answerable challenge questions (post hoc,",
        "not part of the pre-registered protocol):",
        "",
    ]
    for key in ("hit_at_1", "hit_at_3"):
        test = paired[key]
        lines.append(
            f"- {test['metric']}: TF-IDF-only hits {test['only_first_hits']}, BM25-only hits "
            f"{test['only_second_hits']} of {test['paired_questions']}; "
            f"two-sided p = {test['p_value_two_sided']:.4f}"
        )
    lines += [
        "",
        "## Answer or abstain (challenge set)",
        "",
        "The threshold is chosen on dev by the pre-registered rule and applied once to test.",
        "A false answer means an unanswerable question received evidence; a false",
        "abstention means an answerable question received none.",
        "",
        "| Retriever | Threshold (dev) | Test false answers | Test false abstentions | "
        "Answered, wrong evidence | Test, no threshold: false answers |",
        "| --- | ---: | ---: | ---: | ---: | ---: |",
    ]
    for name, result in (("TF-IDF", tfidf), ("BM25", bm25)):
        abstention = result["abstention"]
        test, base = abstention["test"], abstention["test_without_threshold"]
        lines.append(
            f"| {name} | {abstention['selected_threshold_from_dev']:.4f} | "
            f"{test['false_answers']}/{test['unanswerable']} | "
            f"{test['false_abstentions']}/{test['answerable']} | "
            f"{test['answered_with_wrong_evidence']}/{test['answerable']} | "
            f"{base['false_answers']}/{base['unanswerable']} |"
        )
    lines += [
        "",
        "Top-1 score ranges on test (min / median / max):",
        "",
    ]
    for name, result in (("TF-IDF", tfidf), ("BM25", bm25)):
        spread = result["abstention"]["score_distribution_test"]
        ans, unans = spread["answerable"], spread["unanswerable"]
        lines.append(
            f"- {name}: answerable {_fmt(ans['min'])} / {_fmt(ans['median'])} / "
            f"{_fmt(ans['max'])}; unanswerable {_fmt(unans['min'])} / "
            f"{_fmt(unans['median'])} / {_fmt(unans['max'])}"
        )
    lines += [
        "",
        "## Per-question results (challenge test split)",
        "",
        "Rank is the position of the first expected chunk in the top 3 (miss = not retrieved).",
        "",
        "| ID | Design | Expected | TF-IDF top-1 (score) | TF-IDF rank | "
        "BM25 top-1 (score) | BM25 rank |",
        "| --- | --- | --- | --- | ---: | --- | ---: |",
    ]
    bm25_rows = {row["id"]: row for row in bm25["rows"]}
    for row in tfidf["rows"]:
        if row["split"] != "test":
            continue
        other = bm25_rows[row["id"]]

        def top(entry: dict) -> str:
            if not entry["retrieved"]:
                return "none"
            first = entry["retrieved"][0]
            return f"{_short(first['citation'])} ({first['score']:.2f})"

        def rank(entry: dict) -> str:
            if not entry["answerable"]:
                return "-"
            return str(entry["first_relevant_rank"]) if entry["first_relevant_rank"] else "miss"

        expected = ", ".join(_short(c) for c in row["expected_citations"]) or "(unanswerable)"
        lines.append(
            f"| {row['id']} | {row['design']} | {expected} | {top(row)} | {rank(row)} | "
            f"{top(other)} | {rank(other)} |"
        )
    lines += [
        "",
        "## Scope",
        "",
        "Retrieval only: no generator was called, so these numbers say nothing about",
        "answer wording, faithfulness, latency or cost. Labels marked",
        "`ai_drafted_unverified` were drafted with AI assistance and are not yet checked",
        "by a person; treat results as provisional until they are.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Compare lexical retrievers.")
    parser.add_argument("--check", action="store_true", help="fail if committed reports are stale")
    args = parser.parse_args(argv)

    report = build_report()
    rendered_json = json.dumps(report, indent=2, ensure_ascii=False) + "\n"
    rendered_md = render_markdown(report)

    if args.check:
        stale = [
            path.name
            for path, expected in ((JSON_REPORT, rendered_json), (MARKDOWN_REPORT, rendered_md))
            if not path.is_file()
            or path.read_text(encoding="utf-8").replace("\r\n", "\n") != expected
        ]
        if stale:
            print(
                f"STALE: {', '.join(stale)}; run python scripts/compare_retrievers.py",
                file=sys.stderr,
            )
            return 1
        print("retriever comparison reports are current")
        return 0

    JSON_REPORT.parent.mkdir(exist_ok=True)
    JSON_REPORT.write_text(rendered_json, encoding="utf-8")
    MARKDOWN_REPORT.write_text(rendered_md, encoding="utf-8")
    print(rendered_md)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
